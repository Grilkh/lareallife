function exchangeWeaponsWithBox_func ( player, slot, action, curgun, curammo )
	
	slot = tonumber ( MySQL_Save ( slot ) )
	action = MySQL_Save ( action )
	if curgun and curammo then
		curgun = tonumber ( MySQL_Save ( curgun ) )
		curammo = tonumber ( MySQL_Save ( curammo ) )
	end
	if player == client then
		if isOnStateDuty (player) then
			outputChatBox ( "Du bist noch im Dienst!", player, 125, 0, 0 )
			return
		elseif isPedDead ( player ) then
			outputChatBox ( "Du kannst nichts einlagern/entnehmen wenn du tot bist!", player, 125, 0, 0 )
			return
		elseif laGetElementData ( player, "frischabgelegt") == true then
			outputChatBox ( "Bitte warte 5 Sekunden!", player, 125, 0, 0 )
			return
		elseif laGetElementData ( source, "savetimer") == true then
			outputChatBox ( "Du savest gerade!", player, 125, 0, 0 )
			return		
		elseif laGetElementData ( player, "curplayingtime" ) >= 2 then
			if action == "ex" then
				local slot1 = laGetElementData ( player, "gunboxa" )
				local slot2 = laGetElementData ( player, "gunboxb" )
				local slot3 = laGetElementData ( player, "gunboxc" )
				local slot4 = laGetElementData ( player, "gunboxd" )
				local slot5 = laGetElementData ( player, "gunboxe" )
				local slot6 = laGetElementData ( player, "gunboxf" )
				local gun1, ammo1 = gettok ( slot1, 1, string.byte('|') ), gettok ( slot1, 2, string.byte('|') )
				local gun2, ammo2 = gettok ( slot2, 1, string.byte('|') ), gettok ( slot2, 2, string.byte('|') )
				local gun3, ammo3 = gettok ( slot3, 1, string.byte('|') ), gettok ( slot3, 2, string.byte('|') )
				local gun4, ammo4 = gettok ( slot4, 1, string.byte('|') ), gettok ( slot4, 2, string.byte('|') )
				local gun5, ammo5 = gettok ( slot5, 1, string.byte('|') ), gettok ( slot5, 2, string.byte('|') )
				local gun6, ammo6 = gettok ( slot6, 1, string.byte('|') ), gettok ( slot6, 2, string.byte('|') )
				if slot == 1 then
					laSetElementData ( player, "gunboxa", "0|0" )
					giveWeapon ( player, gun1, ammo1, true )
					triggerClientEvent ( player, "sec_gun_give", getRootElement(), gun1, ammo1 )
				elseif slot == 2 then
					laSetElementData ( player, "gunboxb", "0|0" )
					giveWeapon ( player, gun2, ammo2, true )
					triggerClientEvent ( player, "sec_gun_give", getRootElement(), gun2, ammo2 )
				elseif slot == 3 then
					laSetElementData ( player, "gunboxc", "0|0" )
					giveWeapon ( player, gun3, ammo3, true )
					triggerClientEvent ( player, "sec_gun_give", getRootElement(), gun3, ammo3 )
				elseif slot == 4 then
					laSetElementData ( player, "gunboxd", "0|0" )
					giveWeapon ( player, gun4, ammo4, true )
					triggerClientEvent ( player, "sec_gun_give", getRootElement(), gun4, ammo4 )
				elseif slot == 5 then
					laSetElementData ( player, "gunboxe", "0|0" )
					giveWeapon ( player, gun5, ammo5, true )
					triggerClientEvent ( player, "sec_gun_give", getRootElement(), gun5, ammo5 )
				else
					laSetElementData ( player, "gunboxf", "0|0" )
					giveWeapon ( player, gun6, ammo6, true )
					triggerClientEvent ( player, "sec_gun_give", getRootElement(), gun6, ammo6 )
				end
			elseif action == "in" then
				if slot == 1 then
					laSetElementData ( player, "gunboxa", curgun.."|"..curammo )
				elseif slot == 2 then
					laSetElementData ( player, "gunboxb", curgun.."|"..curammo )
				elseif slot == 3 then
					laSetElementData ( player, "gunboxc", curgun.."|"..curammo )
				elseif slot == 4 then
					laSetElementData ( player, "gunboxd", curgun.."|"..curammo )
				elseif slot == 5 then
					laSetElementData ( player, "gunboxe", curgun.."|"..curammo )
				else
					laSetElementData ( player, "gunboxf", curgun.."|"..curammo )
				end
				takeWeapon ( player, curgun )
				if laGetElementData ( player, "playingtime" ) <= 180 and curgun >= 9 then
					banlaPlayerServer ( player, "Waffencheat" )
				end
			end
			triggerClientEvent ( player, "refreshGunCrateBox", getRootElement() )
			laSetElementData ( player, "frischabgelegt", true )
			setTimer ( refresh_frischabgelegt, 5000, 1, player )
		else
			outputChatBox ( "Du musst 2 Minuten warten bis du Waffen einlagern/entnehmen kannst!", player, 125, 0, 0 )
		end
	end
end

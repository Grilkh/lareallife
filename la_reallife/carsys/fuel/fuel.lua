function fillCar ( veh, liters )

	local liters = math.abs ( liters )
	if isElement ( veh ) then
		laSetElementData ( veh, "fuelstate", tonumber ( laGetElementData ( veh, "fuelstate" ) ) + liters )
		local player = getVehicleOccupant ( veh, 0 )
		if player then
			if getElementData ( player, "sprache" ) == "Deutsch" then
				outputChatBox ( "Dein Fahrzeug wurde betankt!", player, 20, 150, 20 )
			else
				outputChatBox ( "Your vehicle has been refueled!", player, 20, 150, 20 )
			end
		end
		setElementFrozen ( veh, false )
	end
end
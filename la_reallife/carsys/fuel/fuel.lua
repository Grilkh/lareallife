function setVehicleNewFuelState ( veh )

	if isElement ( veh ) then
		if getVehicleEngineState ( veh ) then
			local vx, vy, vz = getElementVelocity ( veh )
			if helicopters[getElementModel ( veh )] or planea[getElementModel ( veh )] or planeb[getElementModel ( veh )] then
				vehfactor = 400
			else
				vehfactor = 300
			end
			if laGetElementData ( veh, "fuelSaving" ) then
				vehfactor = vehfactor * 2
			end
			if vehfactor then
				local speed = math.floor ( math.sqrt(vx^2 + vy^2 + vz^2)*214 ) / vehfactor + 0.2
				local newFuel = tonumber ( laGetElementData ( veh, "fuelstate" ) ) - speed
				laSetElementData ( veh, "fuelstate", newFuel )
				if laGetElementData ( veh, "fuelstate" ) <= 0 then
					if getVehicleOccupant ( veh, 0 ) then
						if getElementData ( getVehicleOccupant ( veh, 0 ), "sprache" ) == "Deutsch" then
							outputChatBox ( "Deinem Fahrzeug ist das Benzin ausgegangen - suche dir eine Tankstelle und kauf dir einen Benzinkanister!", getVehicleOccupant ( veh, 0 ), 125, 0, 0 )
						else
							outputChatBox ( "Your vehicle is out of gas - You have to look for a gas station and buy a can of petrol!", getVehicleOccupant ( veh, 0 ), 125, 0, 0 )
						end
					end
					saveBenzinForPrivVeh ( veh )
					laSetElementData ( veh, "engine", false )
					setVehicleEngineState ( veh, false )
					laSetElementData ( veh, "timerrunning", false )
				elseif math.floor(laGetElementData(veh,"fuelstate"))/10 == math.floor(laGetElementData(veh,"fuelstate")/10) then
					saveBenzinForPrivVeh ( veh )
					setTimer ( setVehicleNewFuelState, 10000, 1, veh )
				else
					setTimer ( setVehicleNewFuelState, 10000, 1, veh )
				end
			end
		else
			laSetElementData ( veh, "timerrunning", false )
		end
	end
end

function saveBenzinForPrivVeh ( veh )

	local pname = laGetElementData ( veh, "owner" )
	if pname then
		local slot = laGetElementData ( veh, "carslotnr_owner" )
		MySQL_SetString("vehicles", "Benzin", laGetElementData(_G["privVeh"..pname..slot],"fuelstate"), "Besitzer LIKE '" ..pname.."' AND Slot LIKE '"..slot.."'")
		MySQL_SetString("vehicles", "Distance", laGetElementData(_G["privVeh"..pname..slot],"distance"), "Besitzer LIKE '" ..pname.."' AND Slot LIKE '"..slot.."'")
	end
end

function fillComplete_func ( player, varb )

	if player == client then
		local veh = getPedOccupiedVehicle ( player )
		if veh and getPedOccupiedVehicleSeat ( player ) == 0 then
			local fuel = laGetElementData(veh,"fuelstate")
			if fuel <= 99 then
				if varb then multy = 3 else multy = 1 end
				local costs = math.floor((100-fuel)*literPrice)*multy
				if costs <= laGetElementData ( player, "money" ) then
					takePlayerMoney ( player, costs )
					laSetElementData ( player, "money", laGetElementData ( player, "money" ) - costs )
					triggerClientEvent ( player, "HudEinblendenMoney", getRootElement() )
					setElementFrozen ( veh, true )
					setTimer ( fillCar, 3000, 1, veh, 100-fuel )
					tankeKasse = tankeKasse + math.floor(costs/5)
					--updateBizKasse()
				else
					if getElementData ( player, "sprache" ) == "Deutsch" then
						outputChatBox ( "Du hast nicht genug Geld! Dein Fahrzeug aufzutanken kostet "..costs.." $!", player, 125, 0, 0 )
					else
						outputChatBox ( "You do not have enough money! Fill up your car costs "..costs.." $!", player, 125, 0, 0 )
					end
				end
			else
				if getElementData ( player, "sprache" ) == "Deutsch" then
					outputChatBox ( "Du musst noch nicht tanken!", player, 125, 0, 0 )
				else
					outputChatBox ( "You have not to fill up yet!", player, 125, 0, 0 )
				end
			end
		else
			if getElementData ( player, "sprache" ) == "Deutsch" then
				outputChatBox ( "Du musst noch nicht tanken!", player, 125, 0, 0 )
			else
				outputChatBox ( "You have not to fill up yet!", player, 125, 0, 0 )
			end
		end
	end
end

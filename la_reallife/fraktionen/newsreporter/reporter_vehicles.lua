function ReporterVehicleEnter ( player, seat )

	local veh = source
	if seat == 0 then
		if not isReporter ( player ) then
			opticExitVehicle ( player )
			if getElementData (  player, "sprache" ) == "Deutsch" then
				outputChatBox ( "Du bist kein Reporter!",  player, 125, 0, 0 )
			else
				outputChatBox ( "You're not a reporter!",  player, 125, 0, 0 )			
			end
		end
	end
end
for key, index in pairs ( NewsVehicles ) do
	addEventHandler ( "onVehicleEnter", key, ReporterVehicleEnter )
end


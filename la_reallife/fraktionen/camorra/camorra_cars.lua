function VehicleCamorraEnter ( player, seat )

	local veh = source
	if seat == 0 then
		if not isCamorra ( player ) then
			opticExitVehicle ( player )
			if getElementData ( player, "sprache" ) == "Deutsch" then
				outputChatBox ( "Du bist kein Mitglied der Camorra!", player, 125, 0, 0 )
			else
				outputChatBox ( "You are not a member of the Camorra!", player, 125, 0, 0 )			
			end
		end
	end
end


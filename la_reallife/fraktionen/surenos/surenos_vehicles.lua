	local veh = source
	if getPedOccupiedVehicleSeat ( player ) == 0 then
		if not isSurenos ( player ) then
			opticExitVehicle ( player )
			if getElementData ( player, "sprache" ) == "Deutsch" then
				outputChatBox ( "Du bist kein Mitglied der Surenos!", player, 125, 0, 0 )
			else
				outputChatBox ( "You are not a Member of the Surenos!", player, 125, 0, 0 )			
			end
		end
	end
end


function VehicleCopEnter ( player, seat )

	local veh = source
	source = player
	if getPedOccupiedVehicleSeat ( source ) == 0 then
		if ( stateVehs[veh] or federalVehicles[veh] or armyVehs[veh] ) and getElementModel ( veh ) ~= 520 then
			if copskins[getElementModel ( source )] or fbiSkins[getElementModel(source)] or isArmy ( source ) then
				if not isKeyBound ( source, "sub_mission", "down", policeComputer ) then
					bindKey ( source, "sub_mission", "down", policeComputer )
				end
			else
				opticExitVehicle ( source )
				if getElementData (  source, "sprache" ) == "Deutsch" then
					outputChatBox ( "Du bist kein Beamter in Dienst!",  source, 125, 0, 0 )
				else
					outputChatBox ( "You're not a officer on duty!",  source, 125, 0, 0 )			
				end
			end
		end
	else
		if copskins[getElementModel ( source )] or fbiSkins[getElementModel(source)] or isArmy ( source ) then
			if not isKeyBound ( source, "sub_mission", "down", policeComputer ) then
				bindKey ( source, "sub_mission", "down", policeComputer )
			end
		end
	end
end

function policeComputer ( presser, key, state )

	if state == "down" and ( isOnStateDuty(presser) ) and ( stateVehs[getPedOccupiedVehicle( presser )] or ( armyVehs[getPedOccupiedVehicle( presser )] ) or ( federalVehicles[getPedOccupiedVehicle( presser )] ) ) and getElementModel ( getPedOccupiedVehicle ( presser ) ) ~= 520 then
		triggerClientEvent ( presser,"ShowPoliceComputerGui", getRootElement() )
		setElementData ( presser, "ElementClicked", true )
		showCursor ( presser, true )
		toggleAllControls ( presser, false )
	end
end

function isOnDuty ( player )

	if copskins[getElementModel ( player )] or fbiSkins[getElementModel ( player )] or armySkins[getElementModel ( player )] then
		return true
	else
		return false
	end
end


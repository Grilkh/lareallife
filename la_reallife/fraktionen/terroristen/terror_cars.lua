function VehicleTerrorEnter ( player, seat )

	local veh = source
	if getPedOccupiedVehicleSeat ( player ) == 0 then
		if terrorvehicles[veh] then
			if not isTerror ( player ) then
				opticExitVehicle ( player )
				if getElementData ( player, "sprache" ) == "Deutsch" then
					outputChatBox ( "Du bist kein Terrorist!", player, 125, 0, 0 )
				else
					outputChatBox ( "You are not a terrorist!", player, 125, 0, 0 )			
				end
			end
		end
	end
end
for key, index in pairs ( terrorvehicles ) do
	addEventHandler ( "onVehicleEnter", key, VehicleTerrorEnter )
end
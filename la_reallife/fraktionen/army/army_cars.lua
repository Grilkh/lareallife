function armyVehEnter ( player, seat )

	veh = source
	source = player
	if armyVehs[veh] then
		if isArmy ( source ) and isOnStateDuty ( source ) or seat ~= 0 then
			if getElementModel ( veh ) == 433 then
				setElementHealth ( source, 100 )
				triggerClientEvent ( source, "sec_health_give", getRootElement(), 999 )
				setPedArmor ( source, 100 )
				triggerClientEvent ( source, "sec_armor_give", getRootElement(), 100 )
				triggerClientEvent ( source, "eatSomething", getRootElement() )
			elseif getElementModel ( veh ) == 432 then
				if getElementData ( source, "job" ) ~= "artillerie" then
					opticExitVehicle ( source )
					outputChatBox ( "Du hast nicht die erforderliche Klasse!", source, 125, 0, 0 )
				end
			elseif getElementModel ( veh ) == 425 or getElementModel ( veh ) == 520 then
				if getElementData ( source, "job" ) ~= "luftwaffe" then
					opticExitVehicle ( source )
					outputChatBox ( "Du hast nicht die erforderliche Klasse!", source, 125, 0, 0 )
				else
					giveWeapon ( source, 46, 3, true )
					triggerClientEvent ( source, "sec_gun_give", getRootElement(), 46, 3 )
				end
			elseif getElementModel ( veh ) == 563 or getElementModel ( veh ) == 595 then
				if getElementData ( source, "job" ) ~= "marine" and seat == 0 then
					opticExitVehicle ( source )
					outputChatBox ( "Du hast nicht die erforderliche Klasse!", source, 125, 0, 0 )
				end
			elseif getElementModel ( veh ) == 497 or getElementModel ( veh ) == 427 or getElementModel ( veh ) == 430 or getElementModel ( veh ) == 528 then
				if laGetElementData (source, "armyspecial") == false and seat == 0 then
					opticExitVehicle ( source )
					outputChatBox ( "Du hast nicht die erforderliche Klasse!", source, 125, 0, 0 )
				end
			end
		else
			opticExitVehicle ( source )
			if getElementData ( source, "sprache" ) == "Deutsch" then
				outputChatBox ( "Du bist kein Soldat im Dienst!", source, 125, 0, 0 )
			else
				outputChatBox ( "You're not in the Army!", source, 125, 0, 0 )			
			end
		end
	end
end

for key, index in pairs ( armyVehs ) do
	addEventHandler ( "onVehicleEnter", key, armyVehEnter )
end
function VehicleYakuzaEnter ( player, seat )

	local veh = source
	source = player
	if getPedOccupiedVehicleSeat ( source ) == 0 then
		--if yakuzavehicles[veh] then
			if not isYakuza(source) then
				opticExitVehicle ( source )
				if getElementData ( source, "sprache" ) == "Deutsch" then
					outputChatBox ( "Du bist kein Mitglied der Yakuza!", source, 125, 0, 0 )
				else
					outputChatBox ( "You are not a member of the Yakuza!", source, 125, 0, 0 )			
				end
			end
		--end
	end
end

for key, index in pairs ( yakuzavehicles ) do
	addEventHandler ( "onVehicleEnter", key, VehicleYakuzaEnter )
end

local veh
function createYakuzaVehicle ( model, x, y, z, rx, ry, rz )

	yakuzaVehiclesCounter = yakuzaVehiclesCounter + 1
	veh = createVehicle ( model, x, y, z, rx, ry, rz, "LV-FIN 18" )
	setVehicleColor ( veh, r, g, b )
	setVehiclePaintjob ( veh, 3 )
	toggleVehicleRespawn ( veh, true )
	setVehicleRespawnDelay ( veh, FCarDestroyRespawn*1000*60 )
	setVehicleIdleRespawnDelay ( veh, FCarIdleRespawn*1000*60 )
	addEventHandler ( "onVehicleEnter", veh, VehicleYakuzaEnter )
	
	yakuzaVehicles[yakuzaVehiclesCounter] = veh
	
end
